# -*- coding: utf-8 -*-
"""
بانک روایات روزانه متناسب با وضعیت واقعی کشور (Daily Country Narrative Bank)
انتخاب هوشمند متن‌های داستانی متنوع بر اساس میزان رضایت عمومی، کمبود غلات، نفت یا برق.
"""

import random

CRITICAL_NARRATIVES = [
    "اعتراضات گسترده خیابانی و اعتصابات کارگری در مراکز صنعتی بالا گرفته است. خروج ناگهانی جمعیت از مرزها دولت را در وضعیت هشدار بی‌ثباتی قرار داده است.",
    "تظاهرات ناشی از معیشت و کمبود خدمات پایه، ترافیک مرزی خروج از کشور را به اوج رسانده است. فرماندهان امنیتی خواستار اقدام فوری برای کنترل اوضاع شده‌اند.",
    "بی‌ثباتی اجتماعی و موج مهاجرت نیروهای متخصص، زنگ خطر را برای بوروکراسی و اقتصاد ملی به صدا درآورده است. بازارها با رکود شدید مواجه هستند.",
]

LOW_NARRATIVES = [
    "صف‌های طولانی سوخت و گلایه‌های معیشتی در شهرهای بزرگ دیده می‌شود. مردم خواستار تخصیص اعتبار بیشتر به خدمات عمومی هستند.",
    "افکار عمومی با نگرانی تحرکات اقتصادی را دنبال می‌کند. بازاریان و اتحادیه‌های صنفی خواستار تثبیت قیمت‌ها شده‌اند.",
    "افت شاخص‌های رضایت عمومی، انتقاد رسانه‌های مستقل از مدیریت منابع کشور را به همراه داشته است.",
]

MEDIUM_NARRATIVES = [
    "اوضاع داخلی در حالت تعادل نسبی قرار دارد. فعالیت‌های اقتصادی روان است اما شهروندان چشم‌انتظار توسعه زیرساخت‌های بیشتر هستند.",
    "چرخه تولید و خدمات کشوری با ثبات نسبی ادامه دارد و گزارش‌های روزانه از آرامش در سطح شهرهای اصلی حکایت دارد.",
]

HIGH_NARRATIVES = [
    "مردم با خوش‌بینی کامل رویدادهای ملی را دنبال می‌کنند. رونق بازارها و ثبات معیشتی، روحیه امید و سرمایه‌گذاری را افزایش داده است.",
    "افزایش رضایت عمومی و شاخص‌های مثبت اقتصادی، کشور را در مسیر رشد چشمگیر قرار داده است. اخبار ملی از خوش‌بینی سراسری حکایت دارد.",
    "افتخار ملی و ثبات فوق‌العاده در تمام استان‌ها به چشم می‌خورد. افزایش کیفیت زندگی موجب جلب اعتماد کامل شهروندان شده است.",
]

GRAIN_SHORTAGE_NARRATIVES = [
    "صف‌های نان و کاهش ذخایر غلات موجب نگرانی عمیق خانواده‌ها شده است. گزارش‌های محلی از کمبود مواد غذایی پایه خبر می‌دهند.",
    "کاهش ذخایر گندم فشار مضاعفی بر سفره خانوارها وارد کرده و بخش کشاورزی نیازمند واردات یا احداث فوری مزارع جدید است.",
]

OIL_SHORTAGE_NARRATIVES = [
    "توقف برخی خطوط ترابری به دلیل افت ذخایر سوخت، توجه رسانه‌ها را جلب کرده است. پمپ‌بنزین‌ها با ازدحام مواجه شده‌اند.",
]


def get_daily_narrative(approval: int, grain_ok: bool = True, oil_ok: bool = True) -> str:
    """انتخاب تصادفی یک داستان متناسب با وضعیت واقعی کشور."""
    if not grain_ok:
        return random.choice(GRAIN_SHORTAGE_NARRATIVES)

    if not oil_ok:
        return random.choice(OIL_SHORTAGE_NARRATIVES)

    if approval < 30:
        return random.choice(CRITICAL_NARRATIVES)
    elif approval < 50:
        return random.choice(LOW_NARRATIVES)
    elif approval < 75:
        return random.choice(MEDIUM_NARRATIVES)
    else:
        return random.choice(HIGH_NARRATIVES)
