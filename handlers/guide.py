async def guide_main_menu(update: Update, context: ContextTypes.DEFAULT_TYPE):
    """نمایش منوی اصلی دانشکده و کتابخانه جامع بازی."""
    user = update.effective_user
    user_id = user.id

    c = db.get_country_by_player(user_id)
    c_str = f"رهبر گرامی کشور {c['flag']} <b>{c['name']}</b>" if c else f"بازیکن گرامی <b>{html.escape(user.first_name or 'عزیز')}</b>"

    text = (
        "🏛️ <b>دانشکده و مرکز آموزش عالی «سیاست مدرن»</b>\n"
        "━━━━━━━━━━━━━━━━━━\n\n"
        f"سلام و درود، {c_str}!\n"
        "به جامع‌ترین کتابخانه و مرکز آموزش استراتژی و ژئوپلیتیک بازی خوش آمدید.\n\n"
        "اینجا مانند یک آکادمی نظامی و اقتصادی، تمامی قوانین، فرمول‌ها، مکانیک‌های پنهان و تاکتیک‌های پیروزی در بازی به زبان ساده تدوین شده است.\n\n"
        "📖 <b>لطفاً سرفصل آموزشی مد نظر خود را انتخاب فرمایید:</b>"
    )

    if update.message:
        await update.message.reply_text(text, reply_markup=get_guide_main_keyboard(), parse_mode="HTML")
    elif update.callback_query:
        await update.callback_query.edit_message_text(text, reply_markup=get_guide_main_keyboard(), parse_mode="HTML")


